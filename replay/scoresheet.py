"""Official game scoresheet ("pöytäkirja") as extra material of a Replay. No Qt here (unit-testable).

A scoresheet is NOISY TRUTH: the final score is reliable, but scorer numbers and fouls are written by hand at
the table during the game and contain mistakes, and players who played can be missing. Nothing here overwrites
what the video shows; the sheet fills gaps (names, final score) and is cross-checked against the detections
(:func:`crosscheck`), and every disagreement becomes a "check this" item with a time to jump to.

Readers (:func:`read`):

* **SKL digital scoresheet PDF** (Suomen Koripalloliitto, generated by the federation's system; FIBA layout):
  page "OTTELUYHTEENVETO" (game summary: number, name, points, 1P/2P/3P made, points per quarter J1-J4, fouls,
  coaches PV/AV) is the main source; the FIBA running-score page adds licence numbers, captain, starters,
  players who played, each foul (type, free throws, quarter), team fouls, timeouts, officials, quarter scores
  and the RUNNING SCORE (who scored each point, 1/2/3 points, in order). Text is read with the small built-in
  extractor :mod:`replay.pdftext` (no PDF library needed; ``PDF_BACKEND`` can be swapped).
* **CSV**: one row per player ``team,number,name,points,fouls[,ft,fg2,fg3,q1,q2,q3,q4]`` with optional
  ``# home: X`` / ``# away: Y`` / ``# final: 23-98`` / ``# quarters: 5-24, 10-35, 3-19, 5-20`` comment lines.
* **JSON**: this module's own format (``advanced-analytist/scoresheet@1``, :meth:`Scoresheet.to_dict`).
* Scanned / photographed sheets (images, PDFs without text) raise :class:`ScannedSheetError`: reading
  handwriting needs a text-detection OCR model the user has to approve first.

Per Replay (``projects/<p>/``): the original file is copied to ``scoresheet/<file>``; the parsed sheet goes to
``scoresheet.json`` WITHOUT licence numbers (privacy: the sheet holds minors' names and licence numbers; they
stay in the original file on this computer and are never put into AI prompts or data exports). Both travel
inside ``.aareplay`` packages (the package contains the whole Replay folder).

Uses: :func:`roster_plan` / :func:`apply_roster` fill ``roster.json`` (replay/roster_names.py) - the user's own
names are never overwritten without asking; :func:`write_score_truth` writes ``score_truth.json`` (final +
quarter scores, the format replay/stats.py reconciles) when the Replay covers the whole game; :func:`crosscheck`
compares the sheet with the video detections.

Team sides: sheet team "A" = home (Joukkue A), "B" = away. Video teams are the colour-bound labels "A"/"B" of
replay_data (not necessarily home first); :func:`team_map` maps them using the home/away binding.

CLI: ``python -m replay.scoresheet show <file>`` / ``check <replay folder> [--labels score-labels.json]``.
"""

