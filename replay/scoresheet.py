def main(argv: Iterable[str] | None = None) -> int:
    import argparse

    ap = argparse.ArgumentParser(prog="python -m replay.scoresheet", description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("show", help="parse a scoresheet file and print it (licence numbers hidden)")
    a.add_argument("file")
    a.add_argument("--json", action="store_true")
    b = sub.add_parser("check", help="cross-check a Replay folder (or a results folder) with its scoresheet")
    b.add_argument("replay", help="Replay folder (projects/<p>) or a pass-2 output folder")
    b.add_argument("--sheet", help="scoresheet file (default: the Replay's scoresheet.json)")
    b.add_argument("--labels", help="score-label file with score-bar times (data/benchmark/labels/scores_*.json)")
    b.add_argument("--json", help="write the full report to this JSON file")
    args = ap.parse_args(list(argv) if argv is not None else None)
    if args.cmd == "show":
        s = read(args.file)
        if args.json:
            print(json.dumps(s.to_dict(private=False), indent=2, ensure_ascii=False))
        else:
            print(s.summary())
            for side in TEAMS:
                t = s.teams[side]
                print(f"\n{t.name} ({'home' if side == 'A' else 'away'}): team fouls {t.team_fouls}, "
                      f"timeouts {t.timeouts}")
                for p in t.players:
                    fl = " ".join(f"{f.kind}{f.free_throws or ''}@Q{f.period or '/'.join(map(str, f.periods_possible))}"
                                  for f in p.fouls)
                    print(f"  #{p.number:>3} {p.name:24} {p.points!s:>3} pts  1P {p.ft_made} 2P {p.fg2_made} "
                          f"3P {p.fg3_made}  Q {p.points_by_period}  fouls {p.n_fouls}: {fl}"
                          + ("  (C)" if p.captain else "") + ("  starter" if p.starter else ""))
                for c in t.coaches:
                    print(f"  {c.get('role')}: {c.get('name')}")
            for w in s.warnings:
                print("warning:", w)
        return 0
    root = Path(args.replay)
    proj = root if (root / "results").is_dir() else None
    res = root / "results" if proj else root
    sheet = read(args.sheet) if args.sheet else load(proj or root)
    if sheet is None:
        print("no scoresheet: pass --sheet <file>")
        return 2
    labels = _read_json(Path(args.labels)) if args.labels else None
    replay = _read_json(res / "replay_data.json")
    gs = _read_json(res / "game_state.json")
    rep = crosscheck(proj, sheet, replay, gs, _read_json((proj or root) / "meta.json"), labels)
    print(report_text(sheet, rep))
    if args.json:
        Path(args.json).write_text(json.dumps(rep, indent=2, ensure_ascii=False), encoding="utf-8")
    return 0


