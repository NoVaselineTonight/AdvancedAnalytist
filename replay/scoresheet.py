def replay_duration(root: Path | str, replay: dict | None = None) -> float | None:
    info = _read_json(Path(root) / "project.json") or {}
    d = ((info.get("video_info") or {}).get("duration_s")) if isinstance(info, dict) else None
    if d:
        return float(d)
    ts = (replay or {}).get("t") or []
    return float(ts[-1]) - float(ts[0]) if len(ts) > 1 else None


def score_truth_doc(sheet: Scoresheet, tm: dict[str, str]) -> dict:
    """score_truth.json content (replay/stats.py reconcile format) with VIDEO team labels."""
    doc: dict[str, Any] = {"generated_by": "scoresheet", "source": f"scoresheet ({sheet.source})", "scope": "game",
                           "final": {tm[k]: v for k, v in sheet.final.items()},
                           "names": {tm[k]: sheet.name(k) for k in TEAMS}}
    if sheet.period_scores:
        doc["quarters"] = {tm[k]: v for k, v in sheet.period_scores.items()}
    return doc


def write_score_truth(root: Path | str, sheet: Scoresheet, replay: dict | None = None, meta: dict | None = None,
                      force: bool = False) -> tuple[bool, str]:
    """Write score_truth.json from the sheet when the Replay is the whole game. Never replaces a truth file
    that was not written from a scoresheet unless ``force``. Returns (written, reason)."""
    root = Path(root)
    if not sheet.final:
        return False, "the scoresheet has no final score"
    dur = replay_duration(root, replay)
    if dur is not None and dur < FULL_GAME_MIN_S and not force:
        return False, (f"this Replay is {dur / 60:.0f} min of video, not the whole game: the sheet's final "
                       "score is not used as its score truth (it would make the detected points look missing)")
    f = root / TRUTH_FILE
    old = _read_json(f)
    if isinstance(old, dict) and old.get("generated_by") != "scoresheet" and not force:
        return False, "score_truth.json already exists (not from a scoresheet); not replaced"
    doc = score_truth_doc(sheet, team_map(sheet, replay, meta))
    f.write_text(json.dumps(doc, indent=2, ensure_ascii=False), encoding="utf-8")
    return True, f"score truth written: {sheet.name('A')} {sheet.final.get('A')} - {sheet.final.get('B')} " \
                 f"{sheet.name('B')}"


# ====================================================================================== cross-check
def _f(v: Any) -> float | None:
    try:
        x = float(v)
        return x if math.isfinite(x) else None
    except (TypeError, ValueError):
        return None


def fmt_t(t: float | None) -> str:
    if t is None:
        return "--:--"
    t = max(0.0, float(t))
    h, rem = divmod(int(t), 3600)
    m, s = divmod(rem, 60)
    return f"{h}:{m:02d}:{s:02d}" if h else f"{m}:{s:02d}"


def numbers_seen(replay: dict, gs: dict | None = None) -> dict[str, dict[str, dict]]:
    """Jersey numbers read in the video per video team: {team: {number: {"reads", "tracks", "first_t",
    "seconds"}}} from replay_data track_info (and game-state lineup slot numbers)."""
    out: dict[str, dict[str, dict]] = {"A": {}, "B": {}}
    ts = replay.get("t") or []
    tracks = {str(t.get("id")): t for t in replay.get("tracks") or [] if isinstance(t, dict)}
    for tid, inf in (replay.get("track_info") or {}).items():
        if not isinstance(inf, dict):
            continue
        n = _num(inf.get("number"))
        tr = tracks.get(str(tid)) or {}
        team = inf.get("team") or tr.get("team")
        if not n or team not in TEAMS:
            continue
        xs = tr.get("x") or []
        i0 = int(tr.get("i0") or 0)
        idx = [i for i, v in enumerate(xs) if v is not None]
        first = _f(ts[i0 + idx[0]]) if idx and i0 + idx[0] < len(ts) else None
        step = (float(ts[-1]) - float(ts[0])) / max(1, len(ts) - 1) if len(ts) > 1 else 0.0
        d = out[team].setdefault(n, {"reads": 0, "tracks": [], "first_t": None, "seconds": 0.0})
        d["reads"] += int(inf.get("number_reads") or 1)
        d["tracks"].append(str(tid))
        d["seconds"] = round(d["seconds"] + len(idx) * step, 1)
        if first is not None and (d["first_t"] is None or first < d["first_t"]):
            d["first_t"] = round(first, 2)
    return out


def detected_baskets(replay: dict, gs: dict | None, overrides: dict | None = None) -> list[dict]:
    """Made baskets the video found (timeline-dismissed ones left out): {id, t, team, points, kind, shooter_track,
    shooter_number, confidence}."""
    gs = gs or {}
    ann = gs.get("basket_annotations") or {}
    info = replay.get("track_info") or {}
    out = []
    for e in replay.get("events") or []:
        if not isinstance(e, dict) or e.get("type") != "basket":
            continue
        eid = str(e.get("id"))
        ov = (overrides or {}).get(eid) or {}
        if ov.get("dismissed"):
            continue
        a = ann.get(eid) or {}
        team = ov.get("team") if ov.get("team") in TEAMS else a.get("team") if a.get("team") in TEAMS else \
            e.get("team") if e.get("team") in TEAMS else None
        kind = a.get("kind") or "field_goal"
        pts = int(_f(a.get("points_guess")) or (1 if kind == "free_throw" else 2))
        st = a.get("shooter_track") or ((e.get("details") or {}).get("shooter_track"))
        st = str(st) if st not in (None, "") else None
        num = _num((info.get(st) or {}).get("number")) if st else ""
        out.append({"id": eid, "t": _f(e.get("t")), "team": team, "points": pts, "kind": kind,
                    "shooter_track": st, "shooter_number": num or None, "confidence": _f(e.get("confidence"))})
    out.sort(key=lambda b: b["t"] or 0.0)
    return out


def clip_candidates(sheet: Scoresheet, replay: dict | None, gs: dict | None = None, meta: dict | None = None,
                    max_n: int = 4) -> list[dict]:
    """Where in the game a clip (part of a game) can be: per quarter, the position in the sheet's running score
    where the clip's detected baskets fit best in order (same team, then scorer number, then points); in quarter
    order, the overall best marked "best".
    [{"start_score": [a, b], "period", "seq", "teams_ok", "points_ok", "scorers_ok", "n", "label"}]. Used to let the
    user pin the clip with one click (sets ``sheet.game["replay_start_score"]``) when the order-only match is
    ambiguous. Empty when there is nothing to compare."""
    run = list(sheet.running or [])
    from replay.scorebar import pin_candidate  # a sure score-bar reading pins the clip directly (scorebar.py)
    pinned = pin_candidate(run, gs)
    if pinned is not None:
        return [pinned]
    det = [d for d in detected_baskets(replay or {}, gs) if d.get("team") in TEAMS]
    if not run or not det:
        return []
    tm = team_map(sheet, replay, meta)  # sheet side -> video team
    inv = {v: k for k, v in tm.items()}
    seq = [(inv.get(d["team"]), d.get("points"), d.get("shooter_number")) for d in det]
    n = len(seq)
    out = []
    for i in range(0, max(0, len(run) - n) + 1):
        win = run[i:i + n]
        if len(win) < n:
            break
        teams = sum(1 for (side, _p, _s), ev in zip(seq, win) if side == ev.team)
        pts = sum(1 for (_side, p, _s), ev in zip(seq, win) if p == ev.points)
        scor = sum(1 for (_side, _p, s), ev in zip(seq, win) if s and ev.scorer and _num(s) == _num(ev.scorer))
        prev = run[i - 1] if i > 0 else None
        start = [prev.score_a, prev.score_b] if prev is not None else [0, 0]
        period = win[0].period
        out.append({"start_score": start, "period": period, "seq": win[0].seq, "teams_ok": teams, "points_ok": pts,
                    "scorers_ok": scor, "n": n,
                    "label": (f"Q{period}" if period and period <= 4 else f"OT{period - 4}" if period else "?")
                    + f" from {start[0]}–{start[1]}: {teams}/{n} teams, {scor}/{n} scorer numbers fit"})
    rank = lambda c: (-c["teams_ok"], -c["scorers_ok"], -c["points_ok"], c["seq"])  # noqa: E731
    out.sort(key=rank)
    best: dict = {}  # the best fit inside each quarter: the user picks the quarter, the order picks the moment
    for c in out:
        best.setdefault(c["period"], c)
    res = sorted(best.values(), key=rank)[:max_n]
    if res:
        res[0]["best"] = True
        res[0]["label"] += " (best fit)"
    return sorted(res, key=lambda c: (c["period"] or 99, c["seq"]))


def ft_situations(gs: dict | None, gap_s: float = 45.0) -> list[dict]:
    """Free-throw situations the game state detected: free_throw events / windows grouped per team (attempts
    within ``gap_s`` belong to one trip). {t, t1, team, attempts, made}."""
    gs = gs or {}
    att = []
    for e in gs.get("events") or []:
        if e.get("type") == "free_throw" and _f(e.get("t")) is not None:
            att.append((float(e["t"]), e.get("team"), bool((e.get("details") or {}).get("made"))))
    if not att:
        for w in gs.get("free_throw_windows") or []:
            t = _f(w.get("t0") if isinstance(w, dict) else None)
            if t is not None:
                att.append((t, w.get("team"), False))
    att.sort(key=lambda a: a[0])
    out: list[dict] = []
    for t, team, made in att:
        if out and out[-1]["team"] == team and t - out[-1]["t1"] <= gap_s:
            out[-1]["t1"] = t
            out[-1]["attempts"] += 1
            out[-1]["made"] += int(made)
        else:
            out.append({"t": t, "t1": t, "team": team, "attempts": 1, "made": int(made)})
    return out


def video_periods(gs: dict | None) -> list[dict]:
    try:
        from replay import stats as S
        return S.periods(gs or {})
    except Exception:  # noqa: BLE001
        t0, t1 = ((gs or {}).get("time_range_s") or [0.0, 0.0])[:2]
        return [{"index": 0, "label": "Whole analysed range", "t0": t0, "t1": t1}]


def align(sheet_seq: Sequence[dict], det: Sequence[dict], free_start: bool = False,
          free_end: bool = False) -> list[tuple[int | None, int | None]]:
    """Global alignment of the sheet's scoring order with the detected baskets; ``free_start`` / ``free_end``
    make unaligned sheet entries before / after the detections free (a clip covers part of the game).
    Items: {"team", "points"} (detections may have team None). Returns pairs (sheet index | None, det index | None)
    in order."""
    n, m = len(sheet_seq), len(det)
    GAP_SHEET = -0.4  # a scoring entry the video missed (common: free throws, blocked view)
    GAP_DET = -1.0  # a detection that is not on the sheet (false basket)
    NEG = -1e9

    def sc(a: dict, b: dict) -> float:
        s = 0.0
        if b.get("team") is None:
            s += 0.3
        elif b["team"] == a["team"]:
            s += 2.0
        else:
            s -= 1.5
        pa, pb = a.get("points"), b.get("points")
        if pa and pb:
            s += 0.5 if (pa == 1) == (pb == 1) else -0.5
        return s

    D = [[NEG] * (m + 1) for _ in range(n + 1)]
    P: list[list[int]] = [[0] * (m + 1) for _ in range(n + 1)]
    D[0][0] = 0.0
    for i in range(1, n + 1):
        D[i][0] = 0.0 if free_start else D[i - 1][0] + GAP_SHEET
        P[i][0] = 1
    for j in range(1, m + 1):
        D[0][j] = D[0][j - 1] + GAP_DET
        P[0][j] = 2
    for i in range(1, n + 1):
        for j in range(1, m + 1):
            opts = (D[i - 1][j - 1] + sc(sheet_seq[i - 1], det[j - 1]), D[i - 1][j] + GAP_SHEET,
                    D[i][j - 1] + GAP_DET)
            k = max(range(3), key=lambda x: opts[x])
            D[i][j], P[i][j] = opts[k], k
    i, j = n, m
    if free_end:  # best end row in the last column
        i = max(range(n + 1), key=lambda r: D[r][m])
    out: list[tuple[int | None, int | None]] = []
    for r in range(n, i, -1):
        out.append((r - 1, None))
    while i > 0 or j > 0:
        k = P[i][j] if i > 0 and j > 0 else (1 if j == 0 else 2)
        if k == 0:
            out.append((i - 1, j - 1))
            i, j = i - 1, j - 1
        elif k == 1:
            out.append((i - 1, None))
            i -= 1
        else:
            out.append((None, j - 1))
            j -= 1
    out.reverse()
    return out


def timed_truth(root: Path | str | None, labels: dict | None = None) -> dict | None:
    """Score changes WITH video times for this Replay, when known: a score-label file (benchmark format:
    events [{t_bar, team home/away, points, score_after}], initial_score) passed in, or score_truth.json
    "events" with "t". Returns {"events": [{t, side A|B, points, score: [a, b]}], "initial": [a, b], "lag": s}."""
    doc = labels
    lag = 0.0
    if doc is None and root is not None:
        st = _read_json(Path(root) / TRUTH_FILE)
        if isinstance(st, dict) and any(_f(e.get("t")) is not None for e in st.get("events") or []):
            doc = st
    if not isinstance(doc, dict):
        return None
    init = list(doc.get("initial_score") or [0, 0])[:2]
    a, b = int(init[0] or 0), int(init[1] or 0)
    evs = []
    for e in doc.get("events") or []:
        t = _f(e.get("t_bar") if "t_bar" in e else e.get("t"))
        if t is None:
            continue
        if "t_bar" in e:
            lag = 5.0  # the broadcast score bar changes ~2-9 s after the ball goes through
        tv = str(e.get("team", "")).lower()
        side = "A" if tv in ("home", "a") else "B" if tv in ("away", "b") else None
        pts = int(_f(e.get("points")) or 0)
        sa = e.get("score_after")
        if sa and len(sa) == 2:
            na, nb = int(sa[0]), int(sa[1])
            if side is None:
                side = "A" if na > a else "B"
            pts = pts or (na - a if side == "A" else nb - b)
            a, b = na, nb
        else:
            if side is None:
                continue
            a, b = (a + pts, b) if side == "A" else (a, b + pts)
        evs.append({"t": t - lag, "t_score": t, "side": side, "points": pts, "score": [a, b]})
    return {"events": evs, "initial": [int(init[0] or 0), int(init[1] or 0)], "lag": lag} if evs else None


def crosscheck(root: Path | str | None, sheet: Scoresheet | None = None, replay: dict | None = None,
               gs: dict | None = None, meta: dict | None = None, labels: dict | None = None,
               overrides: dict | None = None) -> dict:
    """Compare the scoresheet with what the video detected. Returns
    {"items": [check-this items {t, kind, severity, title, detail}], "players": per-player rows,
     "baskets": per team/quarter table, "pairs": aligned scoring entries, "notes": [...], "summary": str}."""
    root_p = Path(root) if root is not None else None
    if sheet is None:
        sheet = load(root_p)
    if sheet is None:
        return {"items": [], "players": [], "notes": ["No scoresheet in this Replay."], "summary": "no scoresheet"}
    if replay is None and root_p is not None:
        replay = _read_json(root_p / "results" / "replay_data.json")
    replay = replay if isinstance(replay, dict) else {}
    if gs is None and root_p is not None:
        gs = _read_json(root_p / "results" / "game_state.json")
    gs = gs if isinstance(gs, dict) else {}
    if meta is None and root_p is not None:
        meta = _read_json(root_p / "meta.json")
    if overrides is None and root_p is not None:
        tl = _read_json(root_p / "timeline.json")
        try:
            from replay import stats as S
            overrides = S._overrides(tl)  # noqa: SLF001 - same reading of timeline edits as the stats
        except Exception:  # noqa: BLE001
            overrides = {}
    tm, tm_source = team_map_info(sheet, replay, meta)
    inv = {v: k for k, v in tm.items()}  # video label -> sheet side
    ts = replay.get("t") or []
    t_lo, t_hi = (float(ts[0]), float(ts[-1])) if ts else (0.0, 0.0)
    dur = replay_duration(root_p, replay) if root_p is not None else (t_hi - t_lo or None)
    full_game = dur is not None and dur >= FULL_GAME_MIN_S
    items: list[dict] = []
    notes: list[str] = []

    def item(t: float | None, kind: str, sev: str, title: str, detail: str = "", conf: str = "") -> None:
        items.append({"t": None if t is None else round(float(t), 2), "kind": kind, "severity": sev,
                      "category": CATEGORY.get(kind, "sheet"), "title": title, "detail": detail,
                      "confidence": conf})

    vname = {side: f"{sheet.name(side)}" for side in TEAMS}
    for w in sheet.warnings:
        item(None, "sheet", "info", "Scoresheet disagrees with itself", w, "certain")

    # ---- 1. numbers seen on court vs the sheet's team lists
    seen = numbers_seen(replay, gs)
    for vt in TEAMS:
        side = inv.get(vt)
        if side is None:
            continue
        team = sheet.teams[side]
        other = sheet.teams["B" if side == "A" else "A"]
        for num, d in sorted(seen[vt].items(), key=lambda kv: -kv[1]["reads"]):
            if team.player(num) is not None:
                continue
            reads = d["reads"]
            conf = "likely" if reads >= 10 and d["seconds"] >= 10 else "possible" if reads >= 3 else "weak"
            if conf == "weak":
                continue
            similar = [p.number for p in team.players if _digits_close(p.number, num)]
            hint = (f" It may also be a misread of #{', #'.join(similar)}." if similar else "")
            if other.player(num) is not None:
                hint += f" #{num} is on the {other.name or 'other team'} list (team colour mix-up?)."
            item(d["first_t"], "missing_player", "check" if conf == "likely" else "info",
                 f"#{num} ({vname[side]}) seen on court but not on the scoresheet",
                 f"Number read {reads} times on {len(d['tracks'])} track(s), {d['seconds']:.0f} s on court "
                 f"(tracks {', '.join(d['tracks'][:5])}).{hint}", conf)
        if full_game:
            for p in team.players:
                if p.played and seen[vt].get(p.number) is None:
                    notes.append(f"{vname[side]} #{p.number} {p.name} is on the sheet but the number was never "
                                 "read in the video (numbers are often hard to read; not flagged).")

    # ---- 2. detected baskets vs the sheet
    det = detected_baskets(replay, gs, overrides)
    for b in det:
        b["side"] = inv.get(b["team"]) if b["team"] else None
    fts = ft_situations(gs)
    for f_ in fts:
        f_["side"] = inv.get(f_["team"]) if f_.get("team") else None
    info_tr = replay.get("track_info") or {}
    timed = timed_truth(root_p, labels)
    seq = [{"team": e.team, "points": e.points, "scorer": e.scorer, "score": [e.score_a, e.score_b],
            "period": e.period, "kind": e.kind} for e in sheet.running]
    if not seq:  # no running score (CSV / summary only): nothing to align
        notes.append("The sheet has no running score, so baskets cannot be matched one by one.")
    start_score = sheet.game.get("replay_start_score")
    start_source = "user" if isinstance(start_score, (list, tuple)) and len(start_score) == 2 else None
    pin = None
    if start_source is None and not full_game:  # a sure score-bar reading pins a clip without asking (scorebar.py)
        try:
            from replay.scorebar import pin_candidate
            pin = pin_candidate(list(sheet.running), gs)
        except Exception as e:  # noqa: BLE001 - the order-only match still works
            print("scoresheet: score-bar pin failed:", type(e).__name__, e)
        if pin is not None:
            start_score, start_source = list(pin["start_score"]), "scorebar"
            notes.append(f"Clip position: {pin['label']}.")
    if timed:
        start_score = timed["initial"]
    k0 = 0  # first sheet entry that can be inside this Replay
    if isinstance(start_score, (list, tuple)) and len(start_score) == 2 and seq:
        sa, sb = int(start_score[0]), int(start_score[1])
        k0 = next((i for i, s in enumerate(seq) if s["score"][0] + s["score"][1] > sa + sb), len(seq))
        if not any(s["score"] == [sa, sb] for s in seq) and (sa, sb) != (0, 0):
            item(t_lo, "score_mismatch", "check", f"Score at the start ({sa}-{sb}) is not on the running score", "",
                 "certain")
    pairs_out: list[dict] = []
    window: tuple[int, int] | None = None  # sheet indices covered by this Replay
    if seq and timed:
        # exact: the score after each change identifies the sheet entry; times come from the score bar
        idx_by_score = {(s["score"][0], s["score"][1]): i for i, s in enumerate(seq)}
        tmatch = []
        for e in timed["events"]:
            i = idx_by_score.get(tuple(e["score"]))
            if i is None:
                item(e["t"], "score_mismatch", "check", "Score in the video not found in the sheet's running score",
                     f"score {e['score'][0]}-{e['score'][1]} after a {e['points']}-point change of "
                     f"{vname.get(e['side'], '?')}", "certain")
                continue
            seq[i]["t"] = e["t"]
            seq[i]["t_source"] = "score bar"
            if seq[i]["team"] != e["side"] or seq[i]["points"] != e["points"]:
                item(e["t"], "score_mismatch", "check", "Running score and score bar disagree",
                     f"at {e['score'][0]}-{e['score'][1]} the sheet has {vname[seq[i]['team']]} "
                     f"+{seq[i]['points']} (#{seq[i]['scorer'] or '?'}), the score bar "
                     f"{vname.get(e['side'], '?')} +{e['points']}", "certain")
            tmatch.append(i)
        if tmatch:
            window = (min(tmatch), max(tmatch))
        # detections <-> timed sheet entries by time (ball through the rim ~ score-bar time - lag)
        cand = sorted(((abs((b["t"] or 0) - seq[i]["t"]), i, j) for j, b in enumerate(det) for i in tmatch
                       if b["t"] is not None and -6.5 <= (b["t"] - seq[i]["t"]) <= 3.5), key=lambda x: x[0])
        used_i, used_j, mp = set(), set(), {}
        for _, i, j in cand:
            if i not in used_i and j not in used_j:
                used_i.add(i)
                used_j.add(j)
                mp[j] = i
        pairs = [(mp.get(j), j) for j in range(len(det))] + [(i, None) for i in tmatch if i not in used_i]
        pairs.sort(key=lambda p: (seq[p[0]]["t"] if p[0] is not None else det[p[1]]["t"] or 0.0))
        align_conf = "high"
        notes.append("Basket matching: exact - score-bar times identify every sheet entry (confidence high).")
    elif seq and det:
        free_start = not full_game and k0 == 0
        raw = align(seq[k0:], [{"team": b["side"], "points": b["points"]} for b in det], free_start=free_start,
                    free_end=not full_game)
        pairs = [(None if i is None else i + k0, j) for i, j in raw]
        matched = [i for i, j in pairs if i is not None and j is not None]
        if matched:
            window = (min(matched), max(matched))
        for i, j in pairs:  # times for sheet entries from their matched detections
            if i is not None and j is not None and det[j]["t"] is not None:
                seq[i]["t"] = det[j]["t"]
                seq[i]["t_source"] = "aligned"
        good = sum(1 for i, j in pairs if i is not None and j is not None and det[j]["side"] == seq[i]["team"])
        # order-only matching pairs baskets by team, so it cannot judge the team itself; it is "medium" only
        # for a short Replay whose starting score is known
        align_conf = "medium" if k0 and good >= 1 and len(det) <= 12 else "low"
        notes.append(f"Basket matching: by the order of scoring only, the sheet has no times (confidence "
                     f"{align_conf}).")
        if free_start:
            notes.append("This Replay is part of the game and the score at its start is not known: enter it in the "
                         "Scoresheet window for a reliable match.")
    else:
        pairs, align_conf = [(None, j) for j in range(len(det))], "none"
    notes.insert(0, f"Teams: sheet {sheet.name('A')} = video team {tm['A']}"
                 f" ({video_teams(replay, meta).get(tm['A'], {}).get('colour') or '?'}), {sheet.name('B')} = video "
                 f"team {tm['B']} ({video_teams(replay, meta).get(tm['B'], {}).get('colour') or '?'}); from "
                 f"{tm_source}.")
    sev_pair = "check" if align_conf in ("high", "medium") else "info"
    stats_m = {"sheet_entries": 0, "found": 0, "missed": 0, "extra": 0, "team_ok": 0, "team_bad": 0,
               "scorer_ok": 0, "scorer_bad": 0, "scorer_unread": 0, "ft_found": 0}

    def shooter_num(track: Any) -> str | None:
        if track in (None, ""):
            return None
        return _num((info_tr.get(str(track)) or {}).get("number")) or None

    for i, j in pairs:
        s = seq[i] if i is not None else None
        b = det[j] if j is not None else None
        row: dict[str, Any] = {
            "sheet": None if s is None else {"team": s["team"], "points": s["points"], "scorer": s["scorer"],
                                             "score": s["score"], "period": s["period"], "t": s.get("t")},
            "video": None if b is None else {k: b[k] for k in ("id", "t", "side", "points", "shooter_number",
                                                               "shooter_track", "confidence")}}
        pairs_out.append(row)
        if s is not None and b is not None:
            stats_m["sheet_entries"] += 1
            stats_m["found"] += 1
            if b["side"] is not None and b["side"] != s["team"]:
                stats_m["team_bad"] += 1
                item(b["t"], "basket_team", sev_pair, "Basket credited to the other team in the video",
                     f"video: {vname.get(b['side'], '?')}; sheet: {vname[s['team']]} "
                     f"{s['score'][0]}-{s['score'][1]} (#{s['scorer'] or '?'})", align_conf)
            elif b["side"] is not None:
                stats_m["team_ok"] += 1
            if (b["points"] == 1) != (s["points"] == 1) or (b["points"] in (2, 3) and s["points"] in (2, 3)
                                                             and b["points"] != s["points"]):
                item(b["t"], "basket_points", "info", f"{b['points']} points in the video, {s['points']} on the sheet",
                     f"{vname[s['team']]} {s['score'][0]}-{s['score'][1]}", align_conf)
            _compare_scorer(sheet, s, b["shooter_number"], b["shooter_track"], b["t"], align_conf, sev_pair,
                            stats_m, item, vname)
        elif s is not None and b is None:
            in_range = s.get("t") is None or t_lo - 2 <= s["t"] <= t_hi + 2
            if not in_range or window is None or not window[0] <= i <= window[1]:  # type: ignore[operator]
                continue
            stats_m["sheet_entries"] += 1
            if s["points"] == 1 and s.get("t") is not None:  # a made free throw: look for an FT situation
                near = [f_ for f_ in fts if f_["side"] == s["team"] and f_["t"] - 25 <= s["t"] <= f_["t1"] + 20]
                if near:
                    stats_m["ft_found"] += 1
                    ev = [e for e in gs.get("events") or [] if e.get("type") == "free_throw"
                          and near[0]["t"] - 1 <= (_f(e.get("t")) or -1e9) <= near[0]["t1"] + 1]
                    trk = next(((e.get("details") or {}).get("shooter_track") for e in ev
                                if (e.get("details") or {}).get("shooter_track") not in (None, "")), None)
                    row["video"] = {"free_throw_situation": near[0]["t"], "shooter_track": trk,
                                    "shooter_number": shooter_num(trk)}
                    _compare_scorer(sheet, s, shooter_num(trk), trk, near[0]["t"], align_conf, sev_pair, stats_m,
                                    item, vname)
                    continue
            stats_m["missed"] += 1
            kind = "free throw" if s["points"] == 1 else f"{s['points']}-pointer"
            item(s.get("t"), "missed_basket", "info",
                 f"Sheet {kind} by #{s['scorer'] or '?'} ({vname[s['team']]}) not found in the video",
                 f"score {s['score'][0]}-{s['score'][1]}, quarter {s['period'] or '?'}"
                 + ("" if s.get("t") is not None else "; time unknown"), align_conf)
        elif b is not None:
            stats_m["extra"] += 1
            item(b["t"], "extra_basket", "info", "Detected basket with no matching score on the sheet",
                 f"{vname.get(b['side'], 'team unknown')} +{b['points']} (detector confidence {b['confidence']}); "
                 "probably a false detection", align_conf)
    if stats_m["sheet_entries"]:
        notes.append(f"Scoring entries in this video: {stats_m['sheet_entries']}; detected as baskets "
                     f"{stats_m['found']}, as free-throw situations {stats_m['ft_found']}, not found "
                     f"{stats_m['missed']}; {stats_m['extra']} detections without a sheet entry. "
                     + (f"Team right in {stats_m['team_ok']} of {stats_m['team_ok'] + stats_m['team_bad']}. "
                        if align_conf == "high" else "") + "Scorer number agrees "
                     f"with the video shooter in {stats_m['scorer_ok']} of "
                     f"{stats_m['scorer_ok'] + stats_m['scorer_bad']} comparable "
                     f"({stats_m['scorer_unread']} without a read shooter number).")

    # ---- per team & quarter table
    per = video_periods(gs)
    table = []
    if full_game and len(per) >= 2:
        for qi, p in enumerate(per[:4]):
            row = {"quarter": qi + 1, "t0": p["t0"], "t1": p["t1"]}
            for side in TEAMS:
                vt = tm[side]
                vb = [b for b in det if b["team"] == vt and p["t0"] - 5 <= (b["t"] or -1) < (per[qi + 1]["t0"]
                      if qi + 1 < len(per) else 1e12)]
                sp = (sheet.period_scores.get(side) or [None] * 4)
                sb = [e for e in sheet.running if e.team == side and e.period == qi + 1]
                row[side] = {"sheet_points": sp[qi] if qi < len(sp) else None, "sheet_baskets": len(sb),
                             "sheet_fg": sum(1 for e in sb if e.points >= 2),
                             "video_points": sum(b["points"] for b in vb), "video_baskets": len(vb)}
                d = row[side]
                if d["sheet_points"] is not None and abs(d["video_points"] - d["sheet_points"]) >= 4:
                    item(p["t0"], "quarter_points", "info",
                         f"Q{qi + 1} {vname[side]}: sheet {d['sheet_points']} points, video {d['video_points']}",
                         f"{d['sheet_baskets']} scoring entries on the sheet, {d['video_baskets']} baskets detected "
                         "(video periods are detected breaks; check that they match the quarters)", "medium")
            table.append(row)
        if len(per) != 4:
            notes.append(f"The video has {len(per)} detected periods (not 4): the quarter table is approximate.")
    totals = {side: {"sheet": sheet.final.get(side), "video": sum(b["points"] for b in det if b["side"] == side)}
              for side in TEAMS}

    # ---- fouls vs free-throw situations / stoppages
    sheet_ft_trips = {side: [f for p in sheet.teams["B" if side == "A" else "A"].players for f in p.fouls
                             if (f.free_throws or 0) > 0] for side in TEAMS}  # trips awarded TO side
    ft_made_sheet = {side: [e for e in sheet.running if e.team == side and e.points == 1] for side in TEAMS}
    if full_game:
        for side in TEAMS:
            n_sheet = len(sheet_ft_trips[side])
            n_vid = sum(1 for s in fts if s["side"] == side)
            if n_sheet or n_vid:
                sev = "check" if abs(n_sheet - n_vid) >= 3 else "info"
                item(None, "free_throws", sev,
                     f"{vname[side]} free-throw trips: sheet {n_sheet} (fouls with free throws by the opponent), "
                     f"video {n_vid}", f"{len(ft_made_sheet[side])} free throws made on the running score. "
                     "Free-throw detection misses trips when the shooter or the ball is hidden.", "low")
    for side in TEAMS:  # each timed made free throw should be near a detected FT situation
        for e in [s for s in seq if s["team"] == side and s["points"] == 1 and s.get("t") is not None
                  and s.get("t_source") == "score bar"]:
            if not t_lo - 2 <= e["t"] <= t_hi + 2:
                continue
            near = [s for s in fts if s["t"] - 30 <= e["t"] <= s["t1"] + 20]
            if not near:
                item(e["t"], "free_throws", "info", f"Free throw made by #{e['scorer'] or '?'} ({vname[side]}) - no "
                     "free-throw situation detected around it", f"score {e['score'][0]}-{e['score'][1]}", "medium")
            else:
                opp = "B" if side == "A" else "A"
                fouls_q = [f for p in sheet.teams[opp].players for f in p.fouls if (f.free_throws or 0) > 0
                           and (f.period is None or f.period == e["period"])]
                if not fouls_q:
                    item(e["t"], "foul_missing", "check",
                         f"Free throws for {vname[side]} in Q{e['period']} but no foul with free throws by "
                         f"{vname[opp]} in that quarter on the sheet", "", "medium")
    for s in fts:  # FT situations in the video with no free throws on the sheet nearby (timed only)
        if s["side"] is None or not any(x.get("t_source") == "score bar" for x in seq):
            continue
        near = [e for e in seq if e["team"] == s["side"] and e["points"] == 1 and e.get("t") is not None
                and s["t"] - 20 <= e["t"] <= s["t1"] + 30]
        if not near:
            item(s["t"], "free_throws", "info", f"Free-throw situation for {vname[s['side']]} in the video, no free "
                 "throw made on the sheet near it", f"{s['attempts']} attempt(s) detected; all may have been missed",
                 "low")
    stoppages = [e for e in gs.get("events") or [] if e.get("type") in ("stoppage", "timeout")]
    n_fouls = {side: sum(len(p.fouls) or (p.fouls_total or 0) for p in sheet.teams[side].players) for side in TEAMS}
    if full_game:
        notes.append(f"Fouls on the sheet: {vname['A']} {n_fouls['A']}, {vname['B']} {n_fouls['B']}; the video "
                     f"detected {len(fts)} free-throw situations and {len(stoppages)} other stoppages. Fouls "
                     "without free throws cannot be seen reliably from the video yet (confidence: low).")

    # ---- per player
    players = []
    for side in TEAMS:
        vt = tm[side]
        for p in sheet.teams[side].players:
            vb = [b for b in det if b["team"] == vt and b["shooter_number"] == p.number]
            s_seen = seen[vt].get(p.number)
            players.append({"team": side, "video_team": vt, "number": p.number, "name": p.name,
                            "sheet_points": p.points, "sheet_fouls": p.n_fouls,
                            "sheet_ft": p.ft_made, "sheet_fg2": p.fg2_made, "sheet_fg3": p.fg3_made,
                            "video_points": sum(b["points"] for b in vb), "video_baskets": len(vb),
                            "seen_reads": s_seen["reads"] if s_seen else 0,
                            "seen_s": s_seen["seconds"] if s_seen else 0.0, "starter": p.starter,
                            "captain": p.captain})
        for num, d in seen[vt].items():  # numbers on court not on the sheet
            if sheet.teams[side].player(num) is None and d["reads"] >= 3:
                vb = [b for b in det if b["team"] == vt and b["shooter_number"] == num]
                players.append({"team": side, "video_team": vt, "number": num, "name": "(not on the sheet)",
                                "sheet_points": None, "sheet_fouls": None, "sheet_ft": None, "sheet_fg2": None,
                                "sheet_fg3": None, "video_points": sum(b["points"] for b in vb),
                                "video_baskets": len(vb), "seen_reads": d["reads"], "seen_s": d["seconds"],
                                "starter": False, "captain": False, "missing": True})
    items.sort(key=lambda x: (x["t"] is None, x["t"] or 0.0, x["kind"]))
    n_check = sum(1 for x in items if x["severity"] == "check")
    summary = (f"{n_check} item(s) to check, {len(items) - n_check} minor. Sheet {sheet.final.get('A', '?')}-"
               f"{sheet.final.get('B', '?')}; video baskets {totals['A']['video']}-{totals['B']['video']} points"
               + ("" if full_game else " (this Replay is a part of the game)") + ".")
    return {"items": items, "players": players, "quarters": table, "pairs": pairs_out, "totals": totals,
            "team_map": tm, "team_map_source": tm_source, "full_game": full_game, "notes": notes, "summary": summary,
            "alignment": align_conf, "window": list(window) if window else None, "match_stats": stats_m,
            "start_source": start_source, "pin": pin,
            "sheet_window": [seq[i] for i in range(window[0], window[1] + 1)] if window else []}


