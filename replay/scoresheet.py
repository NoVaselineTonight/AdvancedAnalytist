def _compare_scorer(sheet: Scoresheet, s: dict, vn: str | None, track: Any, t: float | None, conf: str, sev: str,
                    stats_m: dict, item: Callable, vname: dict) -> None:
    sn = s["scorer"]
    if not sn:
        return
    if not vn:
        stats_m["scorer_unread"] += 1
        return
    if sn == vn:
        stats_m["scorer_ok"] += 1
        return
    stats_m["scorer_bad"] += 1
    team = sheet.teams[s["team"]]
    p_s, p_v = team.player(sn), team.player(vn)
    item(t, "scorer", sev, f"Scorer: sheet says #{sn}, video shooter #{vn}",
         f"{vname[s['team']]} {s['score'][0]}-{s['score'][1]}: sheet #{sn} {p_s.name if p_s else ''} / video "
         f"#{vn} {p_v.name if p_v else '(not on the sheet)'} (track {track}). Either the table wrote the wrong "
         "number or the video misread the jersey.", conf)


def _digits_close(a: str, b: str) -> bool:
    """Jersey numbers a reader could confuse: one digit dropped/added or one digit different (21 vs 24, 4 vs 14)."""
    if a == b or not a or not b:
        return False
    if len(a) == len(b):
        return sum(x != y for x, y in zip(a, b)) == 1
    s, l_ = (a, b) if len(a) < len(b) else (b, a)
    return len(l_) - len(s) == 1 and s in (l_[1:], l_[:-1])


def report_text(sheet: Scoresheet, rep: dict) -> str:
    """Plain-text report (CLI / logs). No licence numbers."""
    out = [f"Scoresheet: {sheet.summary()}", rep.get("summary", "")]
    if rep.get("players"):
        out.append("")
        out.append("Team  #   Name                     sheet pts  video pts  fouls  seen reads")
        for p in rep["players"]:
            out.append(f"{sheet.name(p['team'])[:5]:5} {p['number']:>3} {p['name'][:24]:24} "
                       f"{'' if p['sheet_points'] is None else p['sheet_points']:>9} {p['video_points']:>10} "
                       f"{'' if p['sheet_fouls'] is None else p['sheet_fouls']:>6} {p['seen_reads']:>11}")
    if rep.get("items"):
        out.append("")
        out.append("Check these:")
        for it in rep["items"]:
            out.append(f"  [{it['severity']:5}] {fmt_t(it['t']):>7}  {it['title']}"
                       + (f" - {it['detail']}" if it.get("detail") else "")
                       + (f" (confidence {it['confidence']})" if it.get("confidence") else ""))
    for n in rep.get("notes") or []:
        out.append(f"note: {n}")
    return "\n".join(out)


