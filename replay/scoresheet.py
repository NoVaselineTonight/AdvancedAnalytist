# ====================================================================================== data model
@dataclass
class Foul:
    kind: str = "P"  # P T U D C B F (see FOUL_KINDS)
    free_throws: int | None = None  # FTs awarded (the small digit: P1, P2, P3); None = none written
    period: int | None = None  # quarter 1..4 (5+ = overtime) when known
    periods_possible: list[int] = field(default_factory=list)
    color: str | None = None  # "red" (Q1/Q3 on SKL sheets) / "blue" (Q2/Q4) / None
    slot: int = 0  # 1..5 column on the sheet

    def to_dict(self) -> dict:
        return {"kind": self.kind, "free_throws": self.free_throws, "period": self.period,
                "periods_possible": self.periods_possible, "color": self.color, "slot": self.slot}

    @classmethod
    def from_dict(cls, d: dict) -> "Foul":
        return cls(str(d.get("kind") or "P"), _int(d.get("free_throws")), _int(d.get("period")),
                   [int(x) for x in d.get("periods_possible") or []], d.get("color"), int(d.get("slot") or 0))


@dataclass
class SheetPlayer:
    team: str
    number: str
    name: str = ""
    licence: str = ""  # private: never written to scoresheet.json / exports
    captain: bool = False
    starter: bool = False
    played: bool | None = None
    points: int | None = None
    ft_made: int | None = None
    fg2_made: int | None = None
    fg3_made: int | None = None
    points_by_period: list[int] = field(default_factory=list)
    fouls_total: int | None = None  # from the summary page
    fouls: list[Foul] = field(default_factory=list)  # from the running-score page
    sources: list[str] = field(default_factory=list)

    @property
    def n_fouls(self) -> int | None:
        if self.fouls_total is not None:
            return self.fouls_total
        return len(self.fouls) if self.fouls else (0 if self.sources else None)

    def to_dict(self, private: bool = False) -> dict:
        d = {"team": self.team, "number": self.number, "name": self.name, "captain": self.captain,
             "starter": self.starter, "played": self.played, "points": self.points, "ft_made": self.ft_made,
             "fg2_made": self.fg2_made, "fg3_made": self.fg3_made, "points_by_period": self.points_by_period,
             "fouls_total": self.fouls_total, "fouls": [f.to_dict() for f in self.fouls], "sources": self.sources}
        if private and self.licence:
            d["licence"] = self.licence
        return d

    @classmethod
    def from_dict(cls, d: dict) -> "SheetPlayer":
        return cls(str(d.get("team") or ""), _num(d.get("number")), str(d.get("name") or ""),
                   str(d.get("licence") or ""), bool(d.get("captain")), bool(d.get("starter")), d.get("played"),
                   _int(d.get("points")), _int(d.get("ft_made")), _int(d.get("fg2_made")), _int(d.get("fg3_made")),
                   [int(x) for x in d.get("points_by_period") or []], _int(d.get("fouls_total")),
                   [Foul.from_dict(f) for f in d.get("fouls") or [] if isinstance(f, dict)],
                   list(d.get("sources") or []))


@dataclass
class TeamSheet:
    side: str  # "A" home / "B" away
    name: str = ""
    players: list[SheetPlayer] = field(default_factory=list)
    coaches: list[dict] = field(default_factory=list)  # {"role": "head"|"assistant", "name", "fouls"}
    team_fouls: dict[int, int] = field(default_factory=dict)  # quarter -> marked team fouls (max 4 boxes)
    timeouts: list[dict] = field(default_factory=list)  # {"half": 1|2|3, "minute": int, "after_seq": int}

    def player(self, number: Any) -> SheetPlayer | None:
        n = _num(number)
        return next((p for p in self.players if p.number == n), None)

    def to_dict(self, private: bool = False) -> dict:
        coaches = [{k: v for k, v in c.items() if private or k != "licence"} for c in self.coaches]
        return {"side": self.side, "name": self.name, "players": [p.to_dict(private) for p in self.players],
                "coaches": coaches, "team_fouls": {str(k): v for k, v in self.team_fouls.items()},
                "timeouts": self.timeouts}

    @classmethod
    def from_dict(cls, d: dict) -> "TeamSheet":
        return cls(str(d.get("side") or ""), str(d.get("name") or ""),
                   [SheetPlayer.from_dict(p) for p in d.get("players") or [] if isinstance(p, dict)],
                   [dict(c) for c in d.get("coaches") or [] if isinstance(c, dict)],
                   {int(k): int(v) for k, v in (d.get("team_fouls") or {}).items()},
                   [dict(t) for t in d.get("timeouts") or [] if isinstance(t, dict)])


@dataclass
class ScoreEvent:
    """One scoring entry of the running score, in game order."""
    seq: int
    team: str
    points: int
    score_a: int
    score_b: int
    scorer: str | None = None  # jersey number written by the scorer
    kind: str = ""  # "ft" | "fg2" | "fg3" | "" (not marked)
    period: int | None = None

    def score(self, side: str) -> int:
        return self.score_a if side == "A" else self.score_b

    def to_dict(self) -> dict:
        return {"seq": self.seq, "team": self.team, "points": self.points, "score": [self.score_a, self.score_b],
                "scorer": self.scorer, "kind": self.kind, "period": self.period}

    @classmethod
    def from_dict(cls, d: dict) -> "ScoreEvent":
        sc = d.get("score") or [0, 0]
        return cls(int(d.get("seq") or 0), str(d.get("team")), int(d.get("points") or 0), int(sc[0]), int(sc[1]),
                   _num(d.get("scorer")) or None, str(d.get("kind") or ""), _int(d.get("period")))


@dataclass
class Scoresheet:
    source: str = ""
    kind: str = ""  # "skl-pdf" | "csv" | "json"
    game: dict = field(default_factory=dict)  # home, away, date, time, competition, venue, game_number, ...
    officials: dict = field(default_factory=dict)  # referees [names], scorer, timer, shot_clock
    teams: dict[str, TeamSheet] = field(default_factory=lambda: {"A": TeamSheet("A"), "B": TeamSheet("B")})
    period_scores: dict[str, list[int]] = field(default_factory=dict)  # "A" -> [Q1, Q2, Q3, Q4, (OT..)]
    final: dict[str, int] = field(default_factory=dict)
    running: list[ScoreEvent] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)  # the sheet disagrees with itself

    # ---- helpers
    def team(self, side: str) -> TeamSheet:
        return self.teams[side]

    def name(self, side: str) -> str:
        return self.teams[side].name or ("Home" if side == "A" else "Away")

    def n_players(self) -> int:
        return sum(len(t.players) for t in self.teams.values())

    def summary(self) -> str:
        a, b = self.name("A"), self.name("B")
        fin = f" {self.final.get('A', '?')}-{self.final.get('B', '?')}" if self.final else ""
        q = ""
        if self.period_scores.get("A") and self.period_scores.get("B"):
            q = " (" + ", ".join(f"{x}-{y}" for x, y in zip(self.period_scores["A"], self.period_scores["B"])) + ")"
        when = " ".join(x for x in (self.game.get("date"), self.game.get("time")) if x)
        return (f"{a} - {b}{fin}{q}; {len(self.teams['A'].players)} + {len(self.teams['B'].players)} players"
                + (f"; {len(self.running)} scoring entries" if self.running else "") + (f"; {when}" if when else ""))

    def to_dict(self, private: bool = False) -> dict:
        """JSON form. ``private=False`` (default, used for scoresheet.json) leaves licence numbers out."""
        off = dict(self.officials)
        if not private:
            off = {k: (_strip_licence(v) if isinstance(v, str) else [_strip_licence(x) for x in v]
                       if isinstance(v, list) else v) for k, v in off.items()}
        return {"format": FORMAT, "source": self.source, "kind": self.kind, "game": self.game, "officials": off,
                "teams": {k: t.to_dict(private) for k, t in self.teams.items()},
                "period_scores": self.period_scores, "final": self.final,
                "running_score": [e.to_dict() for e in self.running], "warnings": self.warnings}

    @classmethod
    def from_dict(cls, d: dict) -> "Scoresheet":
        if not isinstance(d, dict) or not isinstance(d.get("teams"), dict):
            raise ScoresheetError("not a scoresheet JSON (expected the advanced-analytist/scoresheet@1 format)")
        teams = {k: TeamSheet.from_dict(d["teams"].get(k) or {"side": k}) for k in TEAMS}
        for k in TEAMS:
            teams[k].side = k
        return cls(str(d.get("source") or ""), str(d.get("kind") or "json"), dict(d.get("game") or {}),
                   dict(d.get("officials") or {}), teams,
                   {k: [int(x) for x in v] for k, v in (d.get("period_scores") or {}).items()},
                   {k: int(v) for k, v in (d.get("final") or {}).items() if v is not None},
                   [ScoreEvent.from_dict(e) for e in d.get("running_score") or [] if isinstance(e, dict)],
                   list(d.get("warnings") or []))


def _int(v: Any) -> int | None:
    try:
        return None if v in (None, "", "-") else int(float(v))
    except (TypeError, ValueError):
        return None


def _num(v: Any) -> str:
    """Jersey number text, the same rules as roster_names.norm_number ('07' -> '7', '00' stays)."""
    s = str(v if v is not None else "").strip().lstrip("#").strip()
    if isinstance(v, float) and v == int(v):
        s = str(int(v))
    if s.isdigit() and len(s) > 1 and s.startswith("0") and s.strip("0"):
        s = s.lstrip("0")
    return s


_LIC_RE = re.compile(r"\s+\d{6,}\s*$")


def _strip_licence(s: str) -> str:
    return _LIC_RE.sub("", s or "").strip()


def _split_licence(s: str) -> tuple[str, str]:
    m = re.match(r"^(.*?)\s+(\d{6,})\s*$", s or "")
    return (m.group(1).strip(), m.group(2)) if m else ((s or "").strip(), "")


# ====================================================================================== reading
def read(path: str | Path) -> Scoresheet:
    """Parse a scoresheet file (PDF / CSV / JSON). Raises ScoresheetError with a user-readable message."""
    path = Path(path)
    suf = path.suffix.lower()
    if suf in IMAGE_SUFFIXES:
        raise ScannedSheetError(SCANNED_MSG)
    if not path.exists():
        raise ScoresheetError(f"file not found: {path}")
    data = path.read_bytes()
    if data[:5] == b"%PDF-" or suf == ".pdf":
        sheet = parse_pdf(data)
    elif suf == ".json" or data.lstrip()[:1] == b"{":
        try:
            sheet = Scoresheet.from_dict(json.loads(data.decode("utf-8-sig")))
        except ValueError as e:
            if isinstance(e, ScoresheetError):
                raise
            raise ScoresheetError(f"not valid JSON: {e}") from e
        sheet.kind = sheet.kind or "json"
    elif suf in (".csv", ".txt"):
        sheet = parse_csv(data.decode("utf-8-sig", errors="replace"))
    else:
        raise ScoresheetError(f"unsupported file type {suf or '(none)'}: use the digital PDF, CSV or JSON")
    sheet.source = path.name
    check_internal(sheet)
    return sheet


def parse_pdf(data: bytes | str | Path) -> Scoresheet:
    try:
        pages = PDF_BACKEND(data)
    except pdftext.PdfError as e:
        raise ScoresheetError(f"cannot read the PDF: {e}") from e
    real = [p for p in pages if sum(len(s.text.strip()) for s in p.spans if s.depth == 0) > 20
            or sum(len(s.text.strip()) for s in p.spans) > 200]
    if not real:
        raise ScannedSheetError(SCANNED_MSG)
    sheet = Scoresheet(kind="skl-pdf")
    summary = next((p for p in pages if any("OTTELUYHTEENVETO" in s.text.upper() for s in p.spans)), None)
    running = next((p for p in pages if p is not summary and _looks_running_page(p)), None)
    if summary is None and running is None:
        raise ScoresheetError("this PDF is not a recognised scoresheet (expected the Finnish Basketball "
                              "Federation digital scoresheet with an OTTELUYHTEENVETO page). Use CSV instead.")
    if summary is not None:
        _parse_summary(summary, sheet)
    if running is not None:
        _parse_running_page(running, sheet)
    if not sheet.final and sheet.period_scores.get("A") and sheet.period_scores.get("B"):
        sheet.final = {k: sum(sheet.period_scores[k]) for k in TEAMS}
    return sheet


def _looks_running_page(p: Any) -> bool:
    data = [s for s in p.spans if s.depth == 0]
    lic = sum(1 for s in data if re.fullmatch(r"\d{7,9}", s.text.strip()))
    return lic >= 3 or any("PÖYTÄKIRJA" in s.text.upper() for s in p.spans)


# ---------------------------------------------------------------------------- summary page (OTTELUYHTEENVETO)
def _parse_summary(page: Any, sheet: Scoresheet) -> None:
    lines = page.lines(1.5)
    texts = [" ".join(s.text for s in ln).strip() for ln in lines]
    g = sheet.game
    for ln, t in zip(lines, texts):
        for s in ln:
            st = s.text.strip()
            m = re.match(r"(?i)sarja:\s*(.+)", st)
            if m:
                g["competition"] = m.group(1).strip()
            m = re.match(r"(?i)pelipaikka:\s*(.+)", st)
            if m:
                g["venue"] = m.group(1).strip()
            m = re.match(r"(?i)pvm ja aika:\s*(\S+)\s*(\S*)", st)
            if m:
                g["date"], g["time"] = m.group(1), m.group(2) or g.get("time", "")
            m = re.match(r"(?i)tulos:\s*(\d+)\s*\S\s*(\d+)", st)
            if m:
                sheet.final = {"A": int(m.group(1)), "B": int(m.group(2))}
    header_idx = [i for i, ln in enumerate(lines) if {"No", "Pelaaja"} <= {s.text.strip() for s in ln}]
    if not header_idx:
        sheet.warnings.append("summary page: player table header (No / Pelaaja) not found")
        return
    for k, hi in enumerate(header_idx[:2]):
        side = TEAMS[k]
        team = sheet.teams[side]
        # team name: the nearest line above the header that is a single larger text (size >= 11)
        for j in range(hi - 1, max(-1, hi - 4), -1):
            big = [s for s in lines[j] if s.size >= 11 and s.text.strip() and not set(s.text.strip()) <= {"_"}]
            if big:
                team.name = big[0].text.strip()
                break
        cols = _summary_columns(lines[hi])
        end = header_idx[k + 1] if k + 1 < len(header_idx) else len(lines)
        for ln in lines[hi + 1:end]:
            cells = [s for s in ln if s.text.strip() and not set(s.text.strip()) <= {"_"}]
            if not cells:
                continue
            first = cells[0].text.strip()
            if first.lower().startswith("yhteens"):  # totals row
                tot = _assign(cells[1:], cols)
                if tot.get("points") is not None:
                    team_total = tot["points"]
                    if sheet.final.get(side) is not None and sheet.final[side] != team_total:
                        sheet.warnings.append(f"summary: {team.name} player points add up to {team_total}, "
                                              f"result says {sheet.final[side]}")
                q = [tot.get(f"J{i}") for i in range(1, 9) if tot.get(f"J{i}") is not None]
                if q:
                    sheet.period_scores[side] = q
                tf = tot.get("fouls")
                if tf is not None:
                    sheet.game.setdefault("summary_team_fouls", {})[side] = tf
                break
            name_cells = [s for s in cells[1:] if not re.fullmatch(r"\d+", s.text.strip())]
            name = " ".join(s.text.strip() for s in name_cells)
            vals = _assign([s for s in cells[1:] if re.fullmatch(r"\d+", s.text.strip())], cols)
            if first.upper() in ("PV", "AV", "HC", "AC"):
                team.coaches.append({"role": "head" if first.upper() in ("PV", "HC") else "assistant",
                                     "name": name, "fouls": vals.get("fouls")})
                continue
            if not re.fullmatch(r"\d{1,3}", first):
                continue
            p = SheetPlayer(side, _num(first), name)
            p.points = vals.get("points")
            p.ft_made, p.fg2_made, p.fg3_made = vals.get("1P"), vals.get("2P"), vals.get("3P")
            p.points_by_period = [vals[f"J{i}"] for i in range(1, 9) if vals.get(f"J{i}") is not None]
            p.fouls_total = vals.get("fouls")
            p.played = True
            p.sources.append("summary")
            team.players.append(p)


def _summary_columns(header: list) -> dict[str, float]:
    cols: dict[str, float] = {}
    for s in header:
        t = s.text.strip()
        key = {"Pisteet": "points", "Virheet": "fouls", "1P": "1P", "2P": "2P", "3P": "3P"}.get(t)
        if key is None and re.fullmatch(r"J\d", t):
            key = t
        if key and key not in cols:
            cols[key] = s.x + max(s.width, 0.5 * s.size * len(t)) / 2.0
    return cols


def _assign(cells: list, cols: dict[str, float]) -> dict[str, int]:
    out: dict[str, int] = {}
    if not cols:
        return out
    for s in cells:
        t = s.text.strip()
        if not re.fullmatch(r"\d+", t):
            continue
        cx = s.x + max(s.width, 0.556 * s.size * len(t)) / 2.0
        key = min(cols, key=lambda k: abs(cols[k] - cx))
        if abs(cols[key] - cx) <= 14:
            out[key] = int(t)
    return out


# ---------------------------------------------------------------------------- running-score page
# SKL running-score grid (PDF points); measured from the template's grid lines when they are present.
GRID_COLS = [285.3, 302.3, 320.4, 338.5, 358.6, 378.7, 396.8, 414.9, 435.5, 455.2, 473.2, 491.3, 511.4, 531.6,
             549.6, 567.7, 583.8]
GRID_TOP, GRID_PITCH, GRID_ROWS = 714.25, 14.25, 40


def _color_name(c: tuple[float, float, float]) -> str | None:
    r, g, b = c
    if r > 0.3 and b < 0.25 and g < 0.25:
        return "red"
    if b > 0.3 and r < 0.25:
        return "blue"
    return None


def _grid(page: Any) -> tuple[list[float], float, float]:
    vs = sorted({round(m.x0, 1) for m in page.marks if m.kind == "line" and m.depth > 0 and abs(m.x1 - m.x0) < 0.5
                 and m.x0 > 280 and abs(m.y1 - m.y0) > 300})
    cols = vs if len(vs) >= 17 else GRID_COLS
    if len(cols) > 17:
        cols = cols[-17:]
    hs = sorted({round(m.y0, 2) for m in page.marks if m.kind == "line" and m.depth > 0 and abs(m.y1 - m.y0) < 0.5
                 and m.x0 > 280 and 60 < m.x1 - m.x0 < 90 and m.width < 0.5})
    if len(hs) >= 30:
        diffs = sorted(b - a for a, b in zip(hs, hs[1:]))
        pitch = diffs[len(diffs) // 2]
        if 10 < pitch < 20:
            return cols, max(hs) + pitch, pitch
    return cols, GRID_TOP, GRID_PITCH


def _parse_running_page(page: Any, sheet: Scoresheet) -> None:
    data = [s for s in page.spans if s.depth == 0 and s.text.strip()]
    marks = [m for m in page.marks if m.depth == 0]
    g = sheet.game
    # ---- header (top of the page)
    tops = [s for s in data if s.y > 740]
    names = sorted([s for s in tops if 775 < s.y < 790 and s.size >= 9], key=lambda s: s.x)
    if len(names) >= 2:
        for side, s in zip(TEAMS, (names[0], names[-1])):
            if not sheet.teams[side].name:
                sheet.teams[side].name = s.text.strip()
            g.setdefault("names_upper", {})[side] = s.text.strip()
    refs = []
    for s in sorted(tops, key=lambda s: (-s.y, s.x)):
        t = s.text.strip()
        if not t:
            continue
        if re.fullmatch(r"\d{1,2}\.\d{1,2}\.\d{4}", t):
            g.setdefault("date", t)
        elif re.fullmatch(r"\d{1,2}:\d{2}", t):
            g.setdefault("time", t)
        elif s.x > 300 and s.y < 770 and re.search(r"[A-Za-zÅÄÖåäö]", t):
            refs.append(t)
        elif s.x < 80 and s.y < 755 and re.fullmatch(r"\d+", t):
            g["game_number"] = t
        elif s.x > 450 and s.y > 790 and re.fullmatch(r"\d+", t):
            g["spectators"] = int(t)
        elif s.x < 120 and 755 < s.y < 770 and re.search(r"[A-Za-zÅÄÖ]", t):
            g.setdefault("competition", t)
        elif 120 <= s.x < 300 and s.y < 755 and re.search(r"[A-Za-zÅÄÖ]", t):
            g.setdefault("venue", t)
    if refs:
        sheet.officials["referees"] = refs  # "Name Licence" (licences dropped by to_dict)
    # ---- officials and end of game (bottom right)
    bottom = sorted([s for s in data if s.y < 95 and s.x > 360 and re.search(r"[A-Za-zÅÄÖ]", s.text)],
                    key=lambda s: -s.y)
    for key, s in zip(("scorer", "timer", "shot_clock"), bottom):
        sheet.officials[key] = s.text.strip()
    for s in data:
        if s.y < 40 and re.fullmatch(r"\d{1,2}:\d{2}", s.text.strip()):
            g["ended_at"] = s.text.strip()
    # ---- period scores + final (bottom left box)
    box = [s for s in data if 70 < s.y < 145 and s.x < 280 and re.fullmatch(r"\d+|-", s.text.strip())]
    rows: list[list] = []
    for s in sorted(box, key=lambda s: (-s.y, s.x)):
        if rows and abs(rows[-1][0].y - s.y) < 2:
            rows[-1].append(s)
        else:
            rows.append([s])
    ps: dict[str, list[int]] = {"A": [], "B": []}
    final_row = None
    for r in rows:
        r.sort(key=lambda s: s.x)
        if len(r) == 2 and r[0].y < 90:
            final_row = r
            continue
        for k, s in enumerate(r):
            v = _int(s.text.strip())
            if v is not None:
                ps[TEAMS[k % 2]].append(v)
    if ps["A"] and len(ps["A"]) == len(ps["B"]):
        if sheet.period_scores.get("A") and sheet.period_scores["A"][:4] != ps["A"][:4]:
            sheet.warnings.append(f"quarter scores differ between pages: {sheet.period_scores} vs {ps}")
        sheet.game["period_scores_page1"] = ps
        for k in TEAMS:
            sheet.period_scores.setdefault(k, ps[k])
    if final_row:
        fin = {"A": _int(final_row[0].text), "B": _int(final_row[1].text)}
        if sheet.final and fin != sheet.final:
            sheet.warnings.append(f"final score differs between pages: {sheet.final} vs {fin}")
        if not sheet.final and None not in fin.values():
            sheet.final = {k: int(v) for k, v in fin.items()}  # type: ignore[arg-type]
    # ---- team sections: team label (x ~ 93) below the header; players are licence rows
    upper = {v.strip().casefold() for v in (g.get("names_upper") or {}).values()} |         {t.name.strip().casefold() for t in sheet.teams.values() if t.name}
    labels = sorted([s for s in data if 80 < s.x < 120 and 140 < s.y < 740
                     and s.text.strip().casefold() in upper], key=lambda s: -s.y)
    lic_rows = sorted([s for s in data if s.x < 60 and re.fullmatch(r"\d{6,9}", s.text.strip())], key=lambda s: -s.y)
    if len(labels) >= 2:
        y_a, y_b = labels[0].y, labels[1].y
    elif lic_rows:
        gaps = [(lic_rows[i].y - lic_rows[i + 1].y, i) for i in range(len(lic_rows) - 1)]
        i = max(gaps)[1] if gaps else 0
        y_a, y_b = lic_rows[0].y + 100, (lic_rows[i].y + lic_rows[i + 1].y) / 2 + 60
    else:
        sheet.warnings.append("running-score page: no player rows found")
        return
    sections = {"A": (y_b + 5, y_a + 1), "B": (140.0, y_b + 1)}
    foul_spans_all: list[tuple[Any, str, Foul]] = []
    for side, (lo, hi) in sections.items():
        team = sheet.teams[side]
        rows_t = [s for s in lic_rows if lo < s.y < hi]
        for lic in rows_t:
            row = [s for s in data if abs(s.y - lic.y) < 1.0 and s.x < 280]
            name_s = next((s for s in row if 80 < s.x < 185), None)
            num_s = next((s for s in row if 185 <= s.x < 205 and re.fullmatch(r"\d{1,3}", s.text.strip())), None)
            played = any(205 <= s.x < 220 and s.text.strip().lower() == "x" for s in row)
            starter = any(m.kind == "circle" and 205 < m.cx < 220 and abs(m.cy - (lic.y + 2.5)) < 4 for m in marks)
            raw_name = name_s.text.strip() if name_s else ""
            captain = bool(re.search(r"\((C|K)\)\s*$", raw_name))
            name = re.sub(r"\s*\((C|K)\)\s*$", "", raw_name)
            number = _num(num_s.text) if num_s else ""
            p = team.player(number) if number else None
            if p is None:
                p = SheetPlayer(side, number, name)
                team.players.append(p)
            elif not p.name:
                p.name = name
            p.licence = lic.text.strip()
            p.captain, p.starter = captain, starter
            p.played = played if p.played is None or not played else True
            if "running" not in p.sources:
                p.sources.append("running")
            fouls = sorted([s for s in row if 222 <= s.x < 280 and s.size >= 6
                            and re.fullmatch(r"[PTUDCBF]|GD", s.text.strip())], key=lambda s: s.x)
            p.fouls = []
            for k, fs in enumerate(fouls):
                sub = next((s for s in data if s.size < 6 and 0 < s.x - fs.x < 9 and 0 < lic.y - s.y < 6
                            and re.fullmatch(r"\d", s.text.strip())), None)
                f = Foul(fs.text.strip(), int(sub.text) if sub else None, None, [], _color_name(fs.color), k + 1)
                p.fouls.append(f)
                foul_spans_all.append((fs, side, f))
        # coaches: "Name Licence" texts at x ~ 92 below the players, above the next section
        last_y = min((s.y for s in rows_t), default=hi)
        co = sorted([s for s in data if 88 < s.x < 100 and lo < s.y < last_y - 5 and re.search(r"[A-Za-zÅÄÖ]", s.text)
                     and s.y < hi - 30], key=lambda s: -s.y)
        roles = ("head", "assistant")
        for k, s in enumerate(co[:2]):
            nm, lic_no = _split_licence(s.text)
            existing = next((c for c in team.coaches if c.get("role") == roles[k]), None)
            if existing is None:
                team.coaches.append({"role": roles[k], "name": nm, "licence": lic_no})
            else:
                existing["licence"] = lic_no
                existing.setdefault("name", nm)
        # timeouts (minute numbers in the Aikalisät boxes, left of the team-foul boxes)
        for s in data:
            if 40 < s.x < 105 and hi - 60 < s.y < hi - 25 and re.fullmatch(r"\d{1,2}", s.text.strip()):
                half = 1 if s.y > hi - 42 else 2
                team.timeouts.append({"half": half, "minute": int(s.text), "after_seq": s.seq})
    # ---- team fouls: 'X' boxes; each X follows (in drawing order) the player foul it counts
    xs = sorted([s for s in data if s.text.strip() == "X" and 140 < s.x < 275], key=lambda s: s.seq)
    last_foul: dict[str, tuple[Any, Foul]] = {}
    events = sorted([(fs.seq, "foul", (fs, side, f)) for fs, side, f in foul_spans_all]
                    + [(x.seq, "x", x) for x in xs], key=lambda e: e[0])
    for _, kind, obj in events:
        if kind == "foul":
            fs, side, f = obj
            last_foul[side] = (fs, f)
            continue
        x = obj
        side = next((k for k, (lo, hi) in sections.items() if lo < x.y < hi + 1), None)
        if side is None:
            continue
        hi = sections[side][1]
        upper = x.y > hi - 42
        left = x.x < 205
        q = (1 if left else 2) if upper else (3 if left else 4)
        sheet.teams[side].team_fouls[q] = sheet.teams[side].team_fouls.get(q, 0) + 1
        lf = last_foul.get(side)
        if lf is not None and lf[1].period is None:
            lf[1].period = q
            lf[1].periods_possible = [q]
            last_foul.pop(side, None)
    _infer_foul_periods(sheet)
    # ---- running score
    _parse_running_score(page, data, marks, sheet)


def _infer_foul_periods(sheet: Scoresheet) -> None:
    """Fouls without a team-foul box: quarter from the pen colour (red Q1/Q3, blue Q2/Q4), quarters whose 4
    team-foul boxes were already full, and the order of the player's fouls."""
    for team in sheet.teams.values():
        full = {q for q, n in team.team_fouls.items() if n >= 4}
        any_box = bool(team.team_fouls)
        for p in team.players:
            prev = 1
            for f in p.fouls:
                if f.period is not None:
                    prev = f.period
                    continue
                cand = [1, 2, 3, 4]
                if f.color == "red":
                    cand = [1, 3]
                elif f.color == "blue":
                    cand = [2, 4]
                if any_box and f.kind not in ("C", "B"):
                    cand = [q for q in cand if q in full] or cand
                cand = [q for q in cand if q >= prev] or cand
                f.periods_possible = cand
                if len(cand) == 1:
                    f.period = cand[0]
                    prev = cand[0]
            # backward pass: a later foul's known quarter bounds the earlier ones
            nxt = 99
            for f in reversed(p.fouls):
                if f.period is not None:
                    nxt = f.period
                    continue
                cand = [q for q in f.periods_possible if q <= nxt] or f.periods_possible
                f.periods_possible = cand
                if len(cand) == 1:
                    f.period = cand[0]


def _parse_running_score(page: Any, data: list, marks: list, sheet: Scoresheet) -> None:
    cols, top, pitch = _grid(page)
    bottom = top - GRID_ROWS * pitch
    n_groups = (len(cols) - 1) // 4

    def cell(x: float, y: float) -> tuple[int, int, int] | None:
        """(group, column 0..3 = A#, A score, B score, B#, row 1..40) for a point on the grid."""
        if not (bottom - 2 < y < top + 2) or not (cols[0] - 2 < x < cols[-1] + 2):
            return None
        r = int((top - y) // pitch) + 1
        if not 1 <= r <= GRID_ROWS:
            return None
        for gi in range(n_groups):
            for c in range(4):
                a, b = cols[4 * gi + c], cols[4 * gi + c + 1]
                if a - 1 <= x < b + 1:
                    return gi, c, r
        return None

    numbers = []
    for s in data:
        if not re.fullmatch(r"\d{1,3}", s.text.strip()):
            continue
        c = cell(s.x + max(s.width, 2.0) / 2.0, s.y + s.size * 0.35)
        if c and c[1] in (0, 3):
            numbers.append((s, c))
    by_cell_marks: dict[tuple[int, int, int], list] = {}
    q_ends: dict[str, list[int]] = {"A": [], "B": []}
    three_circles = []
    for m in marks:
        if m.kind == "circle":
            c = cell(m.cx, m.cy)
            if c is None:
                continue
            if c[1] in (1, 2):
                if m.r < 4:
                    by_cell_marks.setdefault(c, []).append(("ft", m))
                else:  # big circle around a score = end of a quarter
                    q_ends["A" if c[1] == 1 else "B"].append(40 * c[0] + c[2])
            else:
                three_circles.append((c, m))
        elif m.kind == "line" and 8 < abs(m.x1 - m.x0) < 25 and 8 < abs(m.y1 - m.y0) < 25:
            c = cell((m.x0 + m.x1) / 2, (m.y0 + m.y1) / 2)
            if c and c[1] in (1, 2):
                by_cell_marks.setdefault(c, []).append(("fg", m))
    entries = []
    used_cells = set()
    for s, (gi, c, r) in numbers:
        team = "A" if c == 0 else "B"
        sc = 1 if c == 0 else 2
        ms = by_cell_marks.get((gi, sc, r), [])
        kind = "ft" if any(k == "ft" for k, _ in ms) else "fg" if ms else ""
        circled = any(cc[0] == gi and cc[1] == c and cc[2] == r for cc, _ in three_circles)
        if circled:
            kind = "fg3"
        used_cells.add((gi, sc, r))
        entries.append({"seq": s.seq, "team": team, "value": 40 * gi + r, "scorer": _num(s.text), "kind": kind,
                        "color": _color_name(s.color)})
    for (gi, sc, r), ms in by_cell_marks.items():  # marks without a scorer number
        if (gi, sc, r) not in used_cells:
            entries.append({"seq": min(m.seq for _, m in ms), "team": "A" if sc == 1 else "B",
                            "value": 40 * gi + r, "scorer": None, "kind": "ft" if ms[0][0] == "ft" else "fg",
                            "color": _color_name(ms[0][1].color)})
            sheet.warnings.append(f"running score: {sheet.name('A' if sc == 1 else 'B')} point {40 * gi + r} "
                                  "has no scorer number")
    if not entries:
        return
    entries.sort(key=lambda e: e["seq"])
    for team in TEAMS:  # drawing order must follow the score; if not, fall back to score order
        vals = [e["value"] for e in entries if e["team"] == team]
        if vals != sorted(vals):
            sheet.warnings.append(f"running score: {sheet.name(team)} entries are not in order on the sheet; "
                                  "using score order")
            ordered = sorted((e for e in entries if e["team"] == team), key=lambda e: e["value"])
            seqs = sorted(e["seq"] for e in ordered)
            for e, sq in zip(ordered, seqs):
                e["seq"] = sq
            entries.sort(key=lambda e: e["seq"])
    score = {"A": 0, "B": 0}
    cum = {k: _cumsum(sheet.period_scores.get(k) or []) for k in TEAMS}
    for k in TEAMS:  # quarter ends from the circles when the box at the bottom is missing
        if not cum[k] and q_ends[k]:
            cum[k] = sorted(set(q_ends[k]))
    for e in entries:
        t = e["team"]
        pts = e["value"] - score[t]
        if pts <= 0:
            sheet.warnings.append(f"running score: {sheet.name(t)} point {e['value']} is not above the previous "
                                  f"score {score[t]}")
            continue
        kind = e["kind"]
        if kind == "ft" and pts != 1:
            sheet.warnings.append(f"running score: free throw mark at {sheet.name(t)} {e['value']} but "
                                  f"{pts} points since the previous entry")
        if kind == "fg3" and pts != 3:
            sheet.warnings.append(f"running score: 3-point circle at {sheet.name(t)} {e['value']} but {pts} points")
        if kind == "fg":
            kind = "fg3" if pts == 3 else "fg2"
        if not kind:
            kind = {1: "ft", 2: "fg2", 3: "fg3"}.get(pts, "")
        score[t] = e["value"]
        period = next((i + 1 for i, c in enumerate(cum[t]) if e["value"] <= c), None) if cum[t] else None
        sheet.running.append(ScoreEvent(len(sheet.running) + 1, t, pts, score["A"], score["B"], e["scorer"], kind,
                                         period))
    # periods for both teams: an entry belongs to the quarter of its team; fill the other side's by order
    _fill_periods(sheet.running)
    for tm in sheet.teams.values():  # timeouts: the score when they were written
        for to in tm.timeouts:
            prev = [e for e in sheet.running if e.seq and _seq_of(entries, e) < to.get("after_seq", 0)]
            to["score"] = [prev[-1].score_a, prev[-1].score_b] if prev else [0, 0]
            to["period"] = prev[-1].period if prev else 1
            to.pop("after_seq", None)


def _seq_of(entries: list[dict], ev: ScoreEvent) -> int:
    i = ev.seq - 1
    return entries[i]["seq"] if 0 <= i < len(entries) else 0


def _cumsum(xs: Sequence[int]) -> list[int]:
    out, s = [], 0
    for x in xs:
        s += x
        out.append(s)
    return out


def _fill_periods(evs: list[ScoreEvent]) -> None:
    """The quarter of an event is known from its own team's quarter totals; it can never be lower than the
    previous event's quarter (game order)."""
    best = 1
    for e in evs:
        if e.period is not None:
            best = max(best, e.period)
            e.period = best if e.period < best else e.period
        else:
            e.period = best


# ---------------------------------------------------------------------------- CSV
def parse_csv(text: str) -> Scoresheet:
    sheet = Scoresheet(kind="csv")
    meta: dict[str, str] = {}
    body = []
    for ln in text.splitlines():
        s = ln.strip()
        if s.startswith("#"):
            m = re.match(r"#\s*([A-Za-z_ ]+)\s*[:=]\s*(.*)", s)
            if m:
                meta[m.group(1).strip().lower()] = m.group(2).strip()
            continue
        if s:
            body.append(ln)
    if not body:
        raise ScoresheetError("the CSV file has no player rows")
    delim = max((";", ",", "\t"), key=body[0].count)
    rows = list(csv.reader(body, delimiter=delim))
    head = [h.strip().lower() for h in rows[0]]
    alias = {"team": ("team", "joukkue", "side"), "number": ("number", "no", "nr", "#", "numero"),
             "name": ("name", "player", "nimi", "pelaaja"), "points": ("points", "pts", "pisteet"),
             "fouls": ("fouls", "pf", "virheet"), "ft": ("ft", "1p", "ftm"), "fg2": ("fg2", "2p"),
             "fg3": ("fg3", "3p"), "q1": ("q1", "j1"), "q2": ("q2", "j2"), "q3": ("q3", "j3"), "q4": ("q4", "j4"),
             "licence": ("licence", "license", "lisenssi")}
    idx = {k: next((i for i, h in enumerate(head) if h in al), None) for k, al in alias.items()}
    if idx["number"] is None or idx["team"] is None:
        raise ScoresheetError("CSV needs a header with at least the columns team,number (and name, points, fouls)")
    sheet.teams["A"].name = meta.get("home", "")
    sheet.teams["B"].name = meta.get("away", "")
    for r in rows[1:]:
        def get(k: str) -> str:
            i = idx.get(k)
            return r[i].strip() if i is not None and i < len(r) else ""
        tv = get("team")
        side = _side_of(tv, sheet)
        if side is None:
            raise ScoresheetError(f"CSV: unknown team '{tv}' (use A/B, home/away or the team names)")
        p = SheetPlayer(side, _num(get("number")), get("name"), get("licence"))
        p.points, p.fouls_total = _int(get("points")), _int(get("fouls"))
        p.ft_made, p.fg2_made, p.fg3_made = _int(get("ft")), _int(get("fg2")), _int(get("fg3"))
        q = [_int(get(f"q{i}")) for i in range(1, 5)]
        p.points_by_period = [x for x in q if x is not None] if any(x is not None for x in q) else []
        p.played = True
        p.sources.append("csv")
        if p.number or p.name:
            sheet.teams[side].players.append(p)
    m = re.match(r"(\d+)\s*[-–:]\s*(\d+)", meta.get("final", ""))
    if m:
        sheet.final = {"A": int(m.group(1)), "B": int(m.group(2))}
    qs = re.findall(r"(\d+)\s*[-–:]\s*(\d+)", meta.get("quarters", ""))
    if qs:
        sheet.period_scores = {"A": [int(a) for a, _ in qs], "B": [int(b) for _, b in qs]}
    if not sheet.final and all(p.points is not None for t in sheet.teams.values() for p in t.players):
        sheet.final = {k: sum(p.points or 0 for p in sheet.teams[k].players) for k in TEAMS}
    for k in ("date", "time", "venue", "competition"):
        if meta.get(k):
            sheet.game[k] = meta[k]
    return sheet


def _side_of(v: str, sheet: Scoresheet) -> str | None:
    t = v.strip().lower()
    if t in ("a", "home", "koti", "kotijoukkue"):
        return "A"
    if t in ("b", "away", "vieras", "vierasjoukkue"):
        return "B"
    for k in TEAMS:
        nm = sheet.teams[k].name.lower()
        if nm and t == nm:
            return k
    for k in TEAMS:  # first unknown team name = home
        if not sheet.teams[k].name:
            sheet.teams[k].name = v.strip()
            return k
    return None


# ---------------------------------------------------------------------------- internal consistency
def check_internal(sheet: Scoresheet) -> list[str]:
    """Add warnings where the sheet disagrees with itself (summary vs running score, fouls, totals)."""
    w = sheet.warnings
    for side in TEAMS:
        team = sheet.teams[side]
        nm = sheet.name(side)
        pts = [p.points for p in team.players if p.points is not None]
        if pts and sheet.final.get(side) is not None and sum(pts) != sheet.final[side]:
            _warn(w, f"{nm}: player points add up to {sum(pts)}, final score says {sheet.final[side]}")
        if sheet.period_scores.get(side) and sheet.final.get(side) is not None \
                and sum(sheet.period_scores[side]) != sheet.final[side]:
            _warn(w, f"{nm}: quarter scores add up to {sum(sheet.period_scores[side])}, final {sheet.final[side]}")
        for p in team.players:
            who = f"{nm} #{p.number}"
            if None not in (p.points, p.ft_made, p.fg2_made, p.fg3_made):
                calc = p.ft_made + 2 * p.fg2_made + 3 * p.fg3_made  # type: ignore[operator]
                if calc != p.points:
                    _warn(w, f"{who}: points {p.points} but 1P/2P/3P give {calc}")
            if p.points_by_period and p.points is not None and sum(p.points_by_period) != p.points:
                _warn(w, f"{who}: points {p.points} but quarters add up to {sum(p.points_by_period)}")
            if p.fouls and p.fouls_total is not None and len(p.fouls) != p.fouls_total:
                _warn(w, f"{who}: {len(p.fouls)} fouls marked on the running-score page, summary says "
                         f"{p.fouls_total}")
        if sheet.running:
            ev = [e for e in sheet.running if e.team == side]
            by: dict[str, list[ScoreEvent]] = {}
            for e in ev:
                by.setdefault(e.scorer or "?", []).append(e)
            for p in team.players:
                rs = by.get(p.number, [])
                rp = sum(e.points for e in rs)
                if p.points is not None and rp != p.points:
                    _warn(w, f"{who_of(sheet, side, p.number)}: running score credits {rp} points, summary says "
                             f"{p.points}")
            for num in by:
                if num != "?" and team.player(num) is None:
                    _warn(w, f"{nm}: running score has scorer #{num} who is not on the team list")
            if ev and sheet.final.get(side) is not None and ev[-1].score(side) != sheet.final[side]:
                _warn(w, f"{nm}: running score ends at {ev[-1].score(side)}, final score {sheet.final[side]}")
    return w


def who_of(sheet: Scoresheet, side: str, number: str) -> str:
    return f"{sheet.name(side)} #{number}"


def _warn(w: list[str], msg: str) -> None:
    if msg not in w:
        w.append(msg)


# ====================================================================================== Replay files
def sheet_path(root: Path | str) -> Path:
    return Path(root) / FILENAME


def load(root: Path | str | None) -> Scoresheet | None:
    """The Replay's parsed scoresheet (scoresheet.json), or None."""
    if root is None:
        return None
    f = sheet_path(root)
    if not f.exists():
        return None
    try:
        d = json.loads(f.read_text(encoding="utf-8"))
        s = Scoresheet.from_dict(d)
        s.game.setdefault("team_map", (d.get("game") or {}).get("team_map"))
        return s
    except (OSError, ValueError):
        return None


def save(root: Path | str, sheet: Scoresheet) -> Path:
    f = sheet_path(root)
    tmp = f.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(sheet.to_dict(private=False), indent=2, ensure_ascii=False), encoding="utf-8")
    tmp.replace(f)
    return f


def original_file(root: Path | str) -> Path | None:
    d = Path(root) / ORIG_DIR
    if not d.is_dir():
        return None
    files = sorted((p for p in d.iterdir() if p.is_file()), key=lambda p: p.stat().st_mtime)
    return files[-1] if files else None


def import_into(root: Path | str, src: Path | str) -> Scoresheet:
    """Parse ``src`` and store it in the Replay: the file is copied to ``scoresheet/`` (replacing an earlier
    one) and the parsed sheet (no licence numbers) to ``scoresheet.json``. Raises ScoresheetError."""
    root, src = Path(root), Path(src)
    sheet = read(src)
    d = root / ORIG_DIR
    d.mkdir(parents=True, exist_ok=True)
    dst = d / src.name
    if src.resolve() != dst.resolve():
        for old in d.iterdir():
            if old.is_file():
                old.unlink()
        shutil.copy2(src, dst)
    sheet.source = f"{ORIG_DIR}/{src.name}"
    sheet.game["imported"] = time.strftime("%Y-%m-%d %H:%M")
    save(root, sheet)
    return sheet


def remove(root: Path | str) -> None:
    root = Path(root)
    sheet_path(root).unlink(missing_ok=True)
    d = root / ORIG_DIR
    if d.is_dir():
        shutil.rmtree(d, ignore_errors=True)
    t = root / TRUTH_FILE
    doc = _read_json(t)
    if isinstance(doc, dict) and str(doc.get("generated_by", "")) == "scoresheet":
        t.unlink(missing_ok=True)


def _read_json(path: Path) -> Any:
    try:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


# ====================================================================================== teams: sheet <-> video
def video_teams(replay: dict | None, meta: dict | None = None) -> dict[str, dict]:
    """{video label: {"name", "side", "colour"}} from replay_data game.teams (fallback meta team binding)."""
    out: dict[str, dict] = {}
    for k, v in (((replay or {}).get("game") or {}).get("teams") or {}).items():
        if k in TEAMS and isinstance(v, dict):
            out[k] = {"name": str(v.get("name") or ""), "side": v.get("side"),
                      "colour": v.get("colour_name") or "", "confirmed": bool(v.get("side_confirmed"))}
    if meta:
        try:
            from replay import team_binding as tbind
            ov = tbind.team_overview(meta)
            for k in TEAMS:
                o = ov.get(k) or {}
                cur = out.setdefault(k, {"name": "", "side": None, "colour": "", "confirmed": False})
                cur["side"] = o.get("side") or cur["side"]
                cur["name"] = o.get("name") or cur["name"]
                cur["colour"] = o.get("colour_name") or cur["colour"]
                cur["confirmed"] = bool(o.get("confirmed")) or cur["confirmed"]
        except Exception:  # noqa: BLE001
            pass
    return out


def team_map(sheet: Scoresheet, replay: dict | None = None, meta: dict | None = None) -> dict[str, str]:
    """Sheet side (A home / B away) -> video team label (see :func:`team_map_info`)."""
    return team_map_info(sheet, replay, meta)[0]


IDENTITY = {"A": "A", "B": "B"}
SWAPPED = {"A": "B", "B": "A"}


def number_evidence(sheet: Scoresheet, replay: dict | None) -> tuple[float, float]:
    """(support for sheet A = video A, support for sheet A = video B) from jersey numbers read in the video:
    reads (capped per number) of numbers that are on only one of the two team lists."""
    if not isinstance(replay, dict):
        return 0.0, 0.0
    seen = numbers_seen(replay)
    nums = {k: {p.number for p in sheet.teams[k].players if p.number} for k in TEAMS}
    only = {k: nums[k] - nums["B" if k == "A" else "A"] for k in TEAMS}
    sup = []
    for m in (IDENTITY, SWAPPED):
        sup.append(float(sum(min(50, seen[m[side]].get(n, {}).get("reads", 0)) for side in TEAMS
                             for n in only[side])))
    return sup[0], sup[1]


COLOUR_WORDS = {  # kit colour words (English / Finnish) -> canonical colour name
    "purple": "purple", "violet": "purple", "violetti": "purple", "lila": "purple", "liila": "purple",
    "orange": "orange", "oranssi": "orange", "red": "red", "punainen": "red", "punaiset": "red",
    "blue": "blue", "sininen": "blue", "siniset": "blue", "navy": "blue", "white": "white", "valkoinen": "white",
    "valkoiset": "white", "black": "black", "musta": "black", "mustat": "black", "green": "green", "vihreä": "green",
    "vihreat": "green", "yellow": "yellow", "keltainen": "yellow", "grey": "grey", "gray": "grey", "harmaa": "grey",
}
NUMBERS_STRONG = 20.0  # number-read support that overrides a confirmed home/away choice (with a prompt)


def _colours_in(text: str) -> set[str]:
    return {COLOUR_WORDS[w] for w in re.findall(r"[a-zäöå]+", (text or "").lower()) if w in COLOUR_WORDS}


def kit_evidence(sheet: Scoresheet, replay: dict | None, meta: dict | None = None) -> tuple[float, float]:
    """(support for identity, support for swapped) from kit colour words in the sheet's team names / colour
    fields vs the colour names of the video teams."""
    vt = video_teams(replay, meta)
    vcol = {k: _colours_in(" ".join([v.get("colour") or "", v.get("name") or ""])) for k, v in vt.items()}
    scol = {k: _colours_in(" ".join([sheet.teams[k].name, str(sheet.game.get(f"colour_{k}") or ""),
                                     str((sheet.game.get("colours") or {}).get(k) or "")])) for k in TEAMS}
    sup = []
    for m in (IDENTITY, SWAPPED):
        sup.append(float(sum(10 for side in TEAMS if scol[side] & vcol.get(m[side], set()))))
    return sup[0], sup[1]


def team_map_suggestion(sheet: Scoresheet, replay: dict | None = None, meta: dict | None = None) -> dict | None:
    """What the video itself says about which sheet team is which kit: jersey numbers read per video team vs each
    sheet roster (+ kit colour words). {"map", "support", "against", "text"} or None when it is not clear."""
    n_id, n_sw = number_evidence(sheet, replay)
    c_id, c_sw = kit_evidence(sheet, replay, meta)
    s_id, s_sw = n_id + c_id, n_sw + c_sw
    hi, lo = max(s_id, s_sw), min(s_id, s_sw)
    if hi < 10 or hi < 2 * lo:
        return None
    m = dict(IDENTITY) if s_id > s_sw else dict(SWAPPED)
    vt = video_teams(replay, meta)
    why = []
    if max(n_id, n_sw) > 0:
        why.append(f"jersey numbers read in the video ({max(n_id, n_sw):.0f} vs {min(n_id, n_sw):.0f} reads)")
    if max(c_id, c_sw) > 0:
        why.append("kit colours named on the sheet")
    names = ", ".join(f"{sheet.teams[side].name or side} = {vt.get(m[side], {}).get('colour') or m[side]}"
                      for side in TEAMS)
    return {"map": m, "support": hi, "against": lo, "text": f"{names} (from {' and '.join(why)})"}


def team_map_info(sheet: Scoresheet, replay: dict | None = None, meta: dict | None = None) -> tuple[dict, str]:
    """(map, source). Order: a manual choice (``sheet.game["team_map"]``); the home/away binding when the user
    confirmed it - unless the jersey numbers read in the video clearly say otherwise (then the numbers win and the
    source says so; the Overview offers the swap, see :func:`home_away_conflict`); jersey numbers / kit colours when
    they clearly fit one way; team names typed by the user; the automatic home/away guess; identity."""
    tm = sheet.game.get("team_map")
    if isinstance(tm, dict) and set(tm) == set(TEAMS) and set(tm.values()) == set(TEAMS):
        return dict(tm), "manual"
    vt = video_teams(replay, meta)
    homes = [k for k, v in vt.items() if v.get("side") == "home"]
    by_side = {"A": homes[0], "B": "B" if homes[0] == "A" else "A"} if len(homes) == 1 else None
    sug = team_map_suggestion(sheet, replay, meta)
    if by_side and all(v.get("confirmed") for v in vt.values()):
        if sug and sug["map"] != by_side and sug["support"] >= NUMBERS_STRONG:
            return sug["map"], "jersey numbers - they contradict the home/away confirmed in Overview: " + sug["text"]
        return by_side, "home/away confirmed in Overview"
    if sug:
        return sug["map"], sug["text"]
    for side in TEAMS:  # names typed by the user that match the sheet
        nm = sheet.teams[side].name.strip().lower()
        hit = [k for k, v in vt.items() if nm and v.get("name", "").strip().lower() == nm]
        if len(hit) == 1:
            other = "B" if hit[0] == "A" else "A"
            return {side: hit[0], ("B" if side == "A" else "A"): other}, "team names"
    if by_side:
        return by_side, "home/away guess (not confirmed)"
    return dict(IDENTITY), "default"


def home_away_conflict(root: Path | str, replay: dict | None = None, meta: dict | None = None) -> dict | None:
    """When a scoresheet is attached and the video's jersey numbers clearly say the home team (sheet side A) wears
    the other kit than the home/away chosen in the Overview: {"home_video_team", "home_name", "away_name",
    "colour", "text"} for a one-click swap prompt. None otherwise (no sheet, manual map, no clear evidence)."""
    sheet = load(root)
    if sheet is None or isinstance(sheet.game.get("team_map"), dict):
        return None
    root = Path(root)
    replay = replay if replay is not None else _read_json(root / "results" / "replay_data.json")
    meta = meta if meta is not None else _read_json(root / "meta.json")
    vt = video_teams(replay, meta)
    homes = [k for k, v in vt.items() if v.get("side") == "home"]
    sug = team_map_suggestion(sheet, replay, meta)
    if sug is None or len(homes) != 1 or sug["map"]["A"] == homes[0] or sug["support"] < NUMBERS_STRONG:
        return None
    k = sug["map"]["A"]
    col = vt.get(k, {}).get("colour") or k
    home, away = sheet.teams["A"].name or "Home", sheet.teams["B"].name or "Away"
    return {"home_video_team": k, "home_name": home, "away_name": away, "colour": col, "why": sug["text"],
            "text": f"The scoresheet suggests {home} (home) = {col}: {sug['text']}. In the Overview the {col} team "
                    f"is set as away."}


# ====================================================================================== roster
def roster_plan(root: Path | str, sheet: Scoresheet, replay: dict | None = None, meta: dict | None = None) -> dict:
    """What filling roster.json from the sheet would change, per video team:
    {"A": {"sheet_side", "team_name", "new": [(num, name)], "conflicts": [(num, roster name, sheet name)],
    "same": n, "has_roster": bool}, "conflicts": total}."""
    from replay import roster_names as rn
    a = rn.load_assignment(root) or rn.Assignment()
    tm = team_map(sheet, replay, meta)
    plan: dict[str, Any] = {"conflicts": 0, "team_map": tm}
    for side in TEAMS:
        vt = tm[side]
        r = a.roster(vt)
        new, conf, same = [], [], 0
        for p in sheet.teams[side].players:
            if not p.number:
                continue
            cur = r.by_number(p.number) if r else None
            if cur is None:
                new.append((p.number, p.name))
            elif _same_name(cur.name, p.name) or not p.name:
                same += 1
            elif not cur.name:
                new.append((p.number, p.name))
            else:
                conf.append((p.number, cur.name, p.name))
        plan[vt] = {"sheet_side": side, "team_name": sheet.name(side), "new": new, "conflicts": conf, "same": same,
                    "has_roster": r is not None, "roster_team": r.team if r else ""}
        plan["conflicts"] += len(conf)
    return plan


def _same_name(a: str, b: str) -> bool:
    na = sorted(re.sub(r"[^\wåäöÅÄÖ]+", " ", a.lower()).split())
    nb = sorted(re.sub(r"[^\wåäöÅÄÖ]+", " ", b.lower()).split())
    return na == nb


def apply_roster(root: Path | str, sheet: Scoresheet, replace_conflicts: bool = False,
                 replay: dict | None = None, meta: dict | None = None) -> dict:
    """Fill the Replay's roster.json from the sheet with the roster_names API. Missing numbers are added and
    empty rosters created; a name the user typed for a number is replaced only when ``replace_conflicts``
    (the GUI asks first). Manual track/slot overrides are never touched. Returns the plan that was applied."""
    from replay import roster_names as rn
    root = Path(root)
    plan = roster_plan(root, sheet, replay, meta)
    a = rn.load_assignment(root) or rn.Assignment()
    for side in TEAMS:
        vt = plan["team_map"][side]
        r = a.roster(vt)
        if r is None:
            r = rn.Roster(team=sheet.name(side), kit="", players=[])
            a.set_roster(vt, r)
        if not r.team:
            r.team = sheet.name(side)
        for p in sheet.teams[side].players:
            if not p.number:
                continue
            cur = r.by_number(p.number)
            if cur is None:
                r.players.append(rn.Player(p.number, p.name))
            elif not cur.name or (replace_conflicts and p.name and not _same_name(cur.name, p.name)):
                cur.name = p.name
        r.players.sort(key=lambda x: (int(x.number) if x.number.isdigit() else 999, x.number))
    rn.save_assignment(root, a)
    plan["applied"] = True
    plan["replaced"] = replace_conflicts
    return plan


